    (re.compile(r"그것만으로도\s*충분"), "'그것만으로도 충분해' 식 뻔한 위로 문구"),
    (re.compile(r"소중한\s*존재"), "'소중한 존재' 식 뻔한 위로 문구"),
    (re.compile(r"모습이\s*(보이네|멋져|멋진|대단|훌륭)"), "'~하는 모습이 멋져' 식 뻔한 위로 문구"),
    (re.compile(r"좋을\s*것\s*같"), "'좋을 것 같아' 같은 딱딱한 말"),
