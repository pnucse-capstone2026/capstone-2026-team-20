    # "쉬어가는 날/시간"류 — 미완 책임(렌즈⑤)을 미덕으로 포장하거나 anchor 없이 뭉뚱그리는
    # 대표적 붕어빵 마무리. "그냥 쉬어가는 날이었던 거야" 식 회피를 잡는다.
    (re.compile(r"쉬어가는\s*(날|시간|중|거)"), "'쉬어가는 날/시간' 식으로 미룸을 미덕으로 포장하거나 anchor 없이 뭉뚱그리는 표현 (렌즈로 판단을 실제로 뒤집을 것)"),
