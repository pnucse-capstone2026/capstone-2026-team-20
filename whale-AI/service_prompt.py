_MAX_SENTENCES = 4
_MAX_CHARS = 160
_MIN_CHARS = 60
# reframe="none"(상실/이별 등 재해석 생략) 케이스는 재해석 문장이 없어서 원래 하한선을 못 채운다.
# 그렇다고 하한선을 아예 없애면 "많이 힘들었겠다." 한 마디로 때우는 걸 못 막으므로,
# 낮지만 실질적인 하한선을 따로 둔다 (최소 공감 문장 + 곁에 있어준다는 문장 정도는 있어야 함).
_MIN_CHARS_NO_REFRAME = 25


def _split_sentences(text: str) -> list[str]:
    # 대략적인 문장 분리 (한국어 구어체 기준, 완벽할 필요 없음)
    parts = re.split(r"(?<=[.!?~])\s+", text.strip())
    return [p for p in parts if p.strip()]


def validate_reply(
    text: str,
    min_chars: int = _MIN_CHARS,
    min_sentences: int = 1,
    require_ending: bool = True,
) -> list[str]:
    """위반 사항 목록을 반환. 비어 있으면 통과."""
    issues: list[str] = []
    sentences = _split_sentences(text)

    if len(sentences) < min_sentences:
        issues.append(
            f"문장이 너무 적음({len(sentences)}문장) → 공감 문장 하나로 끝내지 말고, "
            "지금 이 감정 그대로여도 된다는 뜻의 문장을 diary 상황에 맞게 새로 지어서 하나 더 이어 최소 2문장으로 쓸 것 "
            "('그대로 있어도 괜찮아/돼' 같은 정형 문구를 그대로 쓰지 말고 매번 다르게 표현할 것)"
        )

    # 첫 문장 자체가 "~구나/~겠구나"로 끝나면 잡는다 (첫 문장 예외는 ~겠다/~겠네까지만).
    if sentences and _BANNED_ENDING_FIRST.search(sentences[0].strip()):
        issues.append(
            f"첫 문장 금지 말끝(~구나/~겠구나): 「{sentences[0].strip()[-15:]}」 → "
            "'~겠다/~겠네' 또는 '~나봐/~잖아'로 바꿀 것 (상담사 말투라 금지)"
        )

    # 첫 문장(공감 문장)은 "~겠다/~겠네" 예외 허용이라 검사에서 뺀다.
    for s in sentences[1:]:
        if _BANNED_ENDING.search(s):
            issues.append(f"금지 말끝 사용: 「{s.strip()[-15:]}」 → '~나봐/~잖아/~다구' 계열로 바꿀 것 (첫 문장 제외)")
            break

    if _IMPERATIVE_DAGU.search(text):
        issues.append(
            "명령형에 '~라구/~다구'를 붙여서 문법이 깨짐(예: '마라구', '해라구') → 평서형으로 바꿀 것. "
            "예: '자책하지 마라구' → '자책 안 해도 된다구', '쉬어가라구' → '쉬어가는 것도 필요하다구'"
        )

    m = _STACKED_ENDING.search(text)
    if m:
        issues.append(
            f"이미 완결된 말끝(해체: -았/었/였어 등, 또는 나봐/잖아/거야/아냐) 뒤에 '다구/라구'를 또 겹쳐 붙여서 비문임(예: 「{m.group(0)}」) → "
            "그 말을 '-다'로 끝나는 문장으로 다시 지은 뒤 '구'를 붙일 것 (예: '시간들이었어'+'라구' → '시간들이었다구'). "
            "또는 '다구/라구' 없이 그 말끝 그대로 문장을 끝낼 것"
        )

    if _NOUN_IDAGU.search(text):
        issues.append(
            "명사+이다를 '이다구'로 축약함(비문) → '이라구'로 바꿀 것. 예: '밑거름이다구' → '밑거름이라구'"
        )

    # 말끝 화이트리스트는 더 이상 hard validation으로 쓰지 않는다.
    # "~라구/~다구"는 SYSTEM_PROMPT와 few-shot으로 유지하되, 말끝 하나 때문에
    # GPT를 반복 호출하지 않도록 latency-sensitive path에서는 통과시킨다.

    if len(sentences) > _MAX_SENTENCES:
        issues.append(f"문장 수 초과({len(sentences)}문장) → 2~4문장으로 줄일 것")

    if len(text) > _MAX_CHARS:
        issues.append(f"길이 초과({len(text)}자) → 120자 안팎으로 줄일 것")
    elif len(text) < min_chars:
        issues.append(
            f"너무 짧고 뭉뚱그림({len(text)}자, 최소 {min_chars}자 필요) → 공감 문장 하나로 끝내지 말고 "
            "diary 속 구체적인 상황·표현을 더 담을 것. "
            "일반론('힘들었나봐, 그럴 수도 있지' 식)만 쓰지 말고 원문 내용을 구체적으로 짚을 것"
        )

    for pat, desc in _BANNED_PATTERNS:
        if pat.search(text):
            issues.append(f"금지 표현 사용({desc}) → 빼고 원문 속 구체적 내용으로 대체")
            break

    return issues


def _normalize_ws(s: str) -> str:
    return re.sub(r"\s+", "", s)


