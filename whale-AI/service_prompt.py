_REFRAME_SKIP = "none"
# empathy가 공감이 아니라 바로 반박/반전으로 시작하면 안 됨 (예: "하지만 그건 네 잘못이 아니야"처럼
# 공감 자리에서부터 뒤집으면 유저 감정을 못 들어주고 넘어가는 느낌을 줌).
_EMPATHY_REVERSAL_START = re.compile(r"^(하지만|근데|사실은|그런데)\b")

# anchor 그라운딩 체크용. 조사·어미 차이를 흡수하려고 완전 일치 대신 앞 2글자
# 어간만 맞으면 같은 단어로 본다("야식을"과 "야식은" → 둘 다 "야식"으로 겹침).
_HANGUL_TOKEN = re.compile(r"[가-힣]{2,}")
# 거의 모든 문장에 등장해서 "겹쳤다"는 착시를 주는 접속사·부사·상투 표현.
# 이 토큰들만으로 겹쳤다고 판단하면 그라운딩 체크가 사실상 무력화된다.
_ANCHOR_STOPWORDS = {
    "오늘", "너무", "진짜", "정말", "그냥", "조금", "많이", "계속", "자꾸", "이제",
    "다시", "그리고", "그래서", "그런데", "하지만", "그래도", "이렇게", "그렇게",
    "저렇게", "한테", "에서", "에게", "으로", "까지", "부터", "마다", "처럼", "보다",
    "때문", "생각", "느낌", "마음", "기분", "그건", "이건", "그거", "이거",
}


def _anchor_grounded(anchor: str, text: str) -> bool:
    """reframe/reply가 anchor 속 구체적 단어를 최소 하나 담고 있는지 대략 확인한다.
    완벽한 형태소 분석이 아니라 "그럴 수도 있어"류 붕어빵 답을 거르기 위한 느슨한
    휴리스틱이다 — anchor의 한글 토큰(불용어 제외) 앞 2글자가 text 속 어떤 토큰에도
    없으면 anchor 내용을 하나도 안 가져온 걸로 본다.
    """
    anchor_tokens = [t for t in _HANGUL_TOKEN.findall(anchor) if t not in _ANCHOR_STOPWORDS]
    if not anchor_tokens:
        return True  # anchor에 판단할 실질 토큰이 없으면 오탐 방지 위해 통과시킨다
    text_tokens = _HANGUL_TOKEN.findall(text)
    for a in anchor_tokens:
        stem = a[:2]
        if any(t.startswith(stem) for t in text_tokens):
            return True
    return False


def _parse_structured_reply(raw: str, diary: str) -> tuple[str | None, bool, list[str]]:
    """
    모델이 반환한 JSON({"anchor":..., "appraisal":..., "empathy":..., "reframe":..., "reply":...})을
    파싱하고 anchor가 diary 원문에 실제로 존재하는지, empathy/reframe이 실속 있는지 대조한다.
    appraisal 또는 reframe이 "none"이면(상실·이별 등 재해석하지 않는 경우) reframe 관련 검증은
    건너뛴다 — 둘 중 하나만 none으로 와도 안전하게 skip으로 본다.
    반환: (reply 또는 파싱 실패 시 None, reframe을 건너뛴 케이스인지, 이슈 목록)
    """
    try:
        obj = json.loads(raw)
    except (json.JSONDecodeError, TypeError):
        return None, False, ['JSON 형식 위반 → {"anchor": "...", "appraisal": "...", "empathy": "...", "reframe": "...", "reply": "..."} 형태로만 응답할 것']

    anchor = str(obj.get("anchor") or "").strip()
    appraisal = str(obj.get("appraisal") or "").strip()
    empathy = str(obj.get("empathy") or "").strip()
    reframe = str(obj.get("reframe") or "").strip()
    reply = str(obj.get("reply") or "").strip()

    issues: list[str] = []
    if not reply:
        issues.append("reply 필드가 비어 있음")
    if not anchor or _normalize_ws(anchor) not in _normalize_ws(diary):
        issues.append(
            f"anchor가 원문에 없음(지어낸 근거로 의심됨): 「{anchor}」 → diary 원문에 실제로 있는 문장을 그대로 복사해서 anchor에 넣을 것"
        )
    if not empathy:
        issues.append("empathy 필드가 비어 있음 → anchor의 감정을 그대로 받아주는 순수 공감 문장을 넣을 것")
    elif _EMPATHY_REVERSAL_START.match(empathy):
        issues.append(
            f"empathy가 공감 없이 바로 반박/반전으로 시작함: 「{empathy}」 → '하지만/근데/사실은'으로 시작하지 말고 감정을 그대로 받아주는 문장으로 바꿀 것"
        )

    # appraisal 또는 reframe 어느 쪽이든 "none"이면 재해석 생략 케이스로 본다
    # (상실·비탄·자해위험). 둘 다 봐서 모델이 한쪽만 none으로 흘려도 놓치지 않는다.
    skip_reframe = (
        _normalize_ws(reframe).lower() == _REFRAME_SKIP
        or _normalize_ws(appraisal).lower() == _REFRAME_SKIP
    )

    if not skip_reframe and _harms_another_person(diary):
        issues.append(
            "diary가 타인에게 이미 해를 끼친 행동(폭언/폭력/차별 등)을 담고 있는데 "
            'appraisal/reframe이 "none"이 아님 → 이 행동을 정당화/미화하는 재해석을 '
            '만들면 안 된다. appraisal과 reframe을 모두 "none"으로 바꾸고, reply는 '
            "감정만 짧게 받아준 뒤 행동을 정당화하지 않는 선에서 마무리할 것 "
            "(상대방이 놀랐거나 상처받았을 수 있다는 걸 짧게 짚어주는 정도는 괜찮음)."
        )
    if not skip_reframe:
        if not reframe:
            issues.append(
                'reframe 필드가 비어 있음 → appraisal이 집어낸 판단을 뒤집은 문장을 넣거나, 재해석하면 안 되는 내용이면 "none"을 넣을 것'
            )
        elif any(pat.search(reframe) for pat, _ in _BANNED_PATTERNS):
            issues.append(
                f"reframe이 실속 없는 상투구임: 「{reframe}」 → 그냥 받아주는 말고, appraisal이 집어낸 판단을 구체적으로 뒤집거나 재해석이 안 맞는 내용이면 \"none\"을 넣을 것"
            )

    # anchor 그라운딩: reframe/reply 어디에도 anchor 속 구체적 단어가 하나도 없으면
    # "그럴 수도 있어"류 붕어빵 답일 가능성이 높다. 말투와 달리 이건 이 답변의
    # 핵심 가치(anchor 기반 재해석)가 아예 빠진 경우라 재호출 대상으로 남겨둔다.
    if reply and anchor and not _anchor_grounded(anchor, reply):
        issues.append(
            f"reply에 anchor의 구체적 단어가 하나도 없음(붕어빵 답 의심): anchor「{anchor}」 → "
            "anchor 속 실제 단어·행동·대상(여러 사건이면 다른 사건의 단어도)을 reframe이나 reply에 그대로 가져와서 다시 쓸 것"
        )

    return reply, skip_reframe, issues


def generate_with_guard(
    call_llm,           # callable: messages -> str  (OpenAI 호출 래퍼, JSON 문자열 반환 기대)
    diary: str,
    past_records: list[str] | None = None,
    examples: list[dict] | None = None,
    tone_phrases: list[str] | None = None,
    retry_count: int = 0,
    max_fix_attempts: int = 1,
    on_attempt=None,    # callable: (attempt: int, issues: list[str]) -> None
) -> tuple[str, list[str]]:
    """
    생성 → JSON 파싱 + anchor 근거 대조(구조 검증) → 말투 검증.

    재호출은 구조 검증 실패, 또는 다구/라구가 실제로 비문이 된 경우(_has_grammar_break)에만
    건다 — JSON이 깨졌거나 anchor가 원문에 없는 등 "지어낸 근거"로 의심되는 경우는 그대로
    내보내면 사용자에게 깨진 텍스트나 근거
    없는 내용이 나갈 수 있어서다. 말투/스타일 위반(금지 어미, 길이, 상투구 등)은
    더 이상 재호출 사유가 아니다 — SYSTEM_PROMPT와 few-shot으로만 유도하고, 위반이
    있어도 issues에 담아 로깅만 하고 그대로 반환한다(트래픽이 많을 때는 재호출 한
    번이 곧 지연이라, 되돌릴 수 없는 문제에만 재호출을 쓴다).

    fix_note는 이슈를 한꺼번에 다 넘기면 모델이 한 번에 다 못 고치므로 상위 2개만 넘긴다.
    끝까지 통과 못 하면, 시도들 중 위반 이슈가 가장 적었던 것을 반환한다
    (단순히 마지막/1차로 고정하면, 그게 우연히 제일 부실한 시도여도 그대로 나가버릴 수 있음).
    반환: (최종 텍스트, 검증 이슈 목록 - 비어 있으면 완전 통과, 있으면 참고용 로그)

    on_attempt는 시도가 끝날 때마다 (회차, 그 시도의 위반 목록)으로 불린다.
    재호출 횟수가 곧 응답 지연이라 "몇 번 걸렸나"뿐 아니라 "어떤 규칙에 걸렸나"를
    호출부에서 로깅할 수 있어야 규칙을 손볼 근거가 생긴다. 여기서 직접 print하지
    않는 이유는 eval/play도 이 함수를 쓰는데 거기선 로그가 소음이기 때문이다.
    """
    fix_note = None
    best: tuple[str, list[str]] | None = None
    for attempt in range(1, max_fix_attempts + 2):
        msgs = build_messages(
            diary,
            past_records,
            examples,
            tone_phrases=tone_phrases,
            retry_count=retry_count,
            fix_note=fix_note,
        )
        raw = call_llm(msgs).strip()
        reply, skip_reframe, struct_issues = _parse_structured_reply(raw, diary)

        if reply is None:
            text, issues, need_retry = raw, struct_issues, True
        else:
            if skip_reframe:
                # 급성 상실·비탄: ~다구/~라구 강제 해제(require_ending=False),
                # 대신 시그니처가 붙어 나오면 오히려 잡아낸다.
                content_issues = validate_reply(
                    reply,
                    min_chars=_MIN_CHARS_NO_REFRAME,
                    min_sentences=2,
                    require_ending=False,
                )
                if _SIGNATURE_ENDING.search(reply.strip()):
                    content_issues.append(
                        "급성 상실·비탄 상황엔 '~다구/~라구' 시그니처를 쓰지 말 것 → "
                        "'~어/~야/~어도 돼/곁에 있을게' 같은 따뜻한 평서형 반말로 끝낼 것"
                    )
            else:
                content_issues = validate_reply(reply)
            text, issues = reply, struct_issues + content_issues
            # 금지 말끝·짧은 답변·anchor 미반영도 사용자에게 그대로 노출하면 안 된다.
            need_retry = bool(struct_issues or content_issues) or _has_grammar_break(reply)

        if on_attempt is not None:
            on_attempt(attempt, issues)

        if reply is not None and not need_retry:
            return reply, issues

        if best is None or len(issues) < len(best[1]):
            best = (text, issues)
        fix_note = " / ".join(issues[:2])

    return best  # 끝까지 실패하면 위반이 가장 적었던 시도를 반환 (로깅 권장)