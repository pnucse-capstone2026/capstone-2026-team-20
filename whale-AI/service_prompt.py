    (re.compile(r"자연스러운\s*(일이야|거야|일)"), "'자연스러운 일이야' 같은 딱딱한 말"),
    (re.compile(r"존중해줘"), "'존중해줘' 같은 딱딱한 말"),
    (re.compile(r"(해보는|하는)\s*건\s*어때"), "'~해보는 건 어때' 같은 딱딱한 말"),
    (re.compile(r"(그대로|이대로|그\s*자리에)\s*.{0,10}(괜찮|돼|된)"), "'그대로 ~해도 괜찮아/돼' 식으로 동사만 바꿔서 매번 반복하는 마무리 문구 (표현·문장 구조 자체를 diary마다 다르게 쓸 것)"),
